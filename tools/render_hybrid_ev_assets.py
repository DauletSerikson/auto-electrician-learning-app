def cards(stem,title,items,notes):
    e=[];y=100
    for index,(label,rows,attrs) in enumerate(items):
        data=' '.join(f'data-{key}="{value}"' for key,value in attrs.items())
        e.append(f'<g id="card-{index}" {data}>')
        lines=[(s,18) for s in textwrap.wrap(label,27)]
        lines += [(s,17) for row in rows for s in textwrap.wrap(row,29)]
        height=20+len(lines)*26
        e.append(f'<rect x="14" y="{y}" width="292" height="{height}" rx="6" fill="#eaf3f9" stroke="#193b53"/>')
        yy=y+26
        for s,size in lines:e.append(text(24,yy,s,size));yy+=26
        e.append('</g>');y+=height+24
    frame.write(stem,title,e,y+10,notes)


def flow(stem,title,steps,notes):
    e=[];y=100
    for i,(label,power) in enumerate(steps):
        e.append(f'<g id="flow-{i}" data-power="{power}">')
        e.append(frame.box(20,y,280,50,label));e.append('</g>')
        if i<len(steps)-1:
            e += [line(160,y+50,160,y+76),'<path d="M155,%s L165,%s L160,%s Z" fill="#193b53"/>'%(y+70,y+70,y+80)]
        y+=86
    frame.write(stem,title,e,y,notes)


def curve(e,y,title,points,high,unit,ident,color='#17618b'):
    e.append(text(14,y,title,18));y+=30
    for i in range(7):e.append(line(50+i*40,y,50+i*40,y+160,'#d5e2eb'))
    for i in range(5):e.append(line(50,y+i*40,290,y+i*40,'#d5e2eb'))
    coords=' '.join(f'{50+t/1.2*240:.7f},{y+160-v/high*160:.7f}' for t,v in points)
    e.append(f'<polyline id="{ident}" data-top="{y}" data-high="{high}" data-unit="{unit}" points="{coords}" fill="none" stroke="{color}" stroke-width="2"/>')
    e += [text(4,y+6,f'{high:g}',14),text(28,y+160,'0',14),text(50,y+184,'0',14),text(240,y+184,'1,2 s',14)]
    return y+220


